"""Bundle the pinned ISC full FormData submitter polyfill, with no network at runtime."""
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def build():
    vendor=(ROOT/'third_party/formdata-submitter-polyfill/impl.mjs').read_text(encoding='utf-8')
    export='export{T as a,d as b,f as c};'
    assert vendor.count(export)==1, 'Review upstream exports before upgrading'
    source='// Generated by scripts/build_login_forms.py; formdata-submitter-polyfill 1.0.4 ISC.\n(function(){\n'+vendor.replace(export,'T(d);')+'\n})();\n'
    path=ROOT/'Resources/chatgpt-login-forms.js'
    if not path.exists() or path.read_text(encoding='utf-8')!=source:path.write_text(source,encoding='utf-8')
if __name__=='__main__':build()
