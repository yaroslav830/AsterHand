"""Generate the same public product links for every application."""
import json
from pathlib import Path
import re
ROOT=Path(__file__).resolve().parents[1]
def sync(check=False):
    info=json.loads((ROOT/'Resources/app-info.json').read_text('utf8'))
    assert info['name']=='AsterHand' and info['repositoryUrl'].startswith('https://github.com/')
    if not re.fullmatch(r'https://github\.com/[A-Za-z0-9-]+',info['githubProfileUrl']):
        raise ValueError('Invalid GitHub profile URL')
    js='/* Generated by scripts/sync_app_info.py. */\nwindow.AsterAppInfo='+json.dumps(info,separators=(',',':'))+';\n'
    outputs={ROOT/p:js for p in ['android/app/src/main/assets/ui/app-info.js','desktop/public/app-info.js','desktop/linux/public/app-info.js']}
    url=json.dumps(info['repositoryUrl'])
    profile=json.dumps(info['githubProfileUrl'])
    outputs[ROOT/'Sources/PCAppInfo.h']=(
        '// Generated by scripts/sync_app_info.py.\n#pragma once\n'
        f'#define PCRepositoryURL @{url}\n#define PCGitHubProfileURL @{profile}\n'
    )
    outputs[ROOT/'desktop/windows/AppInfo.cs']=(
        '// Generated by scripts/sync_app_info.py.\nnamespace AsterHand {\n'
        '    internal static class AppInfo {\n'
        f'        internal const string RepositoryUrl = {url};\n'
        f'        internal const string GitHubProfileUrl = {profile};\n'
        '    }\n}\n'
    )
    outputs[ROOT/'android/app/src/main/java/com/pocketagent/AppInfo.java']=(
        '// Generated by scripts/sync_app_info.py.\npackage com.pocketagent;\n'
        'final class AppInfo {\n'
        f'    static final String REPOSITORY_URL = {url};\n'
        f'    static final String GITHUB_PROFILE_URL = {profile};\n'
        '    private AppInfo() {}\n}\n'
    )
    changed=[]
    for p,s in outputs.items():
        if not p.parent.exists():continue
        if not p.exists() or p.read_bytes()!=s.encode('utf8'):
            changed.append(str(p.relative_to(ROOT)))
            if not check:p.write_text(s,encoding='utf8',newline='\n')
    if check and changed:raise SystemExit('App info out of sync: '+', '.join(changed))
    return changed
if __name__=='__main__':
    import sys
    print(sync('--check' in sys.argv))
