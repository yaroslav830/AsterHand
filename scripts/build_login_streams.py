"""Build one offline login resource from the pinned MIT stream implementation."""
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def build():
    vendor=(ROOT/'third_party/web-streams-polyfill/ponyfill.js').read_text(encoding='utf-8')
    shim=(ROOT/'Resources/chatgpt-login-streams-shim.js').read_text(encoding='utf-8')
    source="// Generated by scripts/build_login_streams.py; bundled web-streams-polyfill MIT.\n(function(){\nif(typeof window.TextEncoderStream==='function'&&typeof window.TextDecoderStream==='function')return;\nvar module={exports:{}};var exports=module.exports;\n"+vendor+'\n'+shim+'\n})();\n'
    destination=ROOT/'Resources/chatgpt-login-streams.js'
    if not destination.exists() or destination.read_text(encoding='utf-8')!=source:destination.write_text(source,encoding='utf-8')
if __name__=='__main__':build()
