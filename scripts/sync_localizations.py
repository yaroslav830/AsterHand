"""Validate the shared UI catalog and generate offline JavaScript bundles."""
import argparse
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[1]
LANGUAGES = ['en', 'ja', 'es', 'fr']
TARGETS = ['desktop/public/i18n.js', 'android/app/src/main/assets/ui/i18n.js']


def sync(check=False):
    from sync_user_guide import sync as sync_user_guide
    if (ROOT / "Resources/user-guide.json").exists():
        sync_user_guide(check)
    catalog = json.loads((ROOT / 'Resources/localizations.json').read_text('utf-8'))
    printf = re.compile(r'%(?:\d+\$)?[-+0 #]*(?:\d+|\*)?(?:\.(?:\d+|\*))?(?:hh|ll|[hljztL])?[@diuoxXfFeEgGaAcCsSp%]')
    named = re.compile(r'\{[a-zA-Z0-9_]+\}')
    for source, translations in catalog['messages'].items():
        assert set(translations) == set(LANGUAGES), f'Missing language: {source}'
        for language, value in translations.items():
            assert isinstance(value, str) and value.strip(), f'Empty {language}: {source}'
            if language == 'en':
                assert not re.search(r'[\u3400-\u4dbf\u4e00-\u9fff]', value), f'Chinese text in English translation: {source}'
            assert sorted(printf.findall(source)) == sorted(printf.findall(value)), f'Format mismatch {language}: {source}'
            assert sorted(named.findall(source)) == sorted(named.findall(value)), f'Parameter mismatch {language}: {source}'
    runtime = (ROOT / 'scripts/localization-runtime.js').read_text('utf-8')
    bundle = '// Generated by scripts/sync_localizations.py; edit Resources/localizations.json.\nwindow.AsterI18nCatalog = ' + json.dumps(catalog, ensure_ascii=False, separators=(',', ':')) + ';\n' + runtime
    for target in TARGETS:
        path = ROOT / target
        if not path.parent.exists():continue
        if check:
            assert path.read_text('utf-8') == bundle, f'Stale catalog: {target}'
        else:
            path.write_text(bundle, encoding='utf-8')
    destination = ROOT / 'android/app/src/main/assets/localizations.json'
    if not destination.parent.exists():
        print(f'{len(catalog["messages"])} messages validated')
        return
    data = (ROOT / 'Resources/localizations.json').read_bytes()
    if check:
        assert destination.read_bytes() == data, 'Stale Android native catalog'
    else:
        destination.write_bytes(data)
    print(f'{len(catalog["messages"])} messages validated in {len(LANGUAGES) + 1} languages')


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    sync(parser.parse_args().check)
