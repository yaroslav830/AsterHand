"""Validate shared mobile help content and bundle it for the offline Android UI."""
import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def sync(check=False):
    guide = json.loads((ROOT / 'Resources/user-guide.json').read_text('utf-8'))
    messages = json.loads((ROOT / 'Resources/localizations.json').read_text('utf-8'))['messages']
    assert guide['version'] == 1 and len(guide['steps']) == 5
    ids = [topic['id'] for topic in guide['topics']]
    assert len(ids) == len(set(ids))
    for entry in guide['steps'] + guide['topics']:
        for key, value in entry.items():
            if key in ('id', 'icon', 'symbol', 'iosImage', 'androidImage'):
                continue
            for source in value if isinstance(value, list) else [value]:
                assert source in messages, f'Missing guide translation: {source}'
        for platform in ('ios', 'android'):
            image = entry.get(platform + 'Image')
            if image:
                source = ROOT / 'Resources/Guide' / Path(image).name
                assert source.is_file(), f'Missing guide image: {source}'
                if platform == 'android':
                    destination = ROOT / 'android/app/src/main/assets/ui' / image
                    if not (ROOT / "android/app/src/main/assets/ui").exists():continue
                    if check:
                        assert destination.read_bytes() == source.read_bytes(), f'Stale guide image: {image}'
                    else:
                        destination.parent.mkdir(parents=True, exist_ok=True)
                        shutil.copyfile(source, destination)
    bundle = '// Generated by scripts/sync_user_guide.py; edit Resources/user-guide.json.\nwindow.AsterUserGuide = ' + json.dumps(guide, ensure_ascii=False, separators=(',', ':')) + ';\n'
    target = ROOT / 'android/app/src/main/assets/ui/user-guide.js'
    if not target.parent.exists():return
    if check:
        assert target.read_text('utf-8') == bundle, 'Stale Android user guide'
    else:
        target.write_text(bundle, encoding='utf-8')
    print(f'Mobile user guide: {len(guide["steps"])} steps, {len(ids)} topics')


if __name__ == '__main__':
    import argparse
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    sync(parser.parse_args().check)
